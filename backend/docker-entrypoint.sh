#!/bin/sh
# Стартует контейнер от root (это нормально — root нужен только на долю секунды
# здесь, чтобы поправить владельца тома данных), затем передаёт управление java
# от имени непривилегированного пользователя appuser (см. Dockerfile).
#
# chown -R нужен, потому что именованный том backend_data мог быть создан ещё
# ДО этого изменения (когда контейнер работал от root) — тогда все файлы внутри
# него принадлежат root, и appuser не сможет их читать/писать без этого шага.
# На пустом/новом томе chown отрабатывает мгновенно.
set -e
chown -R appuser:appuser /app/data
exec su -s /bin/sh appuser -c 'exec java -jar /app/app.jar'
